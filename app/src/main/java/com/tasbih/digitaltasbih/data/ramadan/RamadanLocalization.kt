    fun get(langCode: String): RamadanStringsData {
        val code = langCode.lowercase().split("-")[0].trim()
        return when (code) {
            "hi" -> hi
            "ur" -> ur
            "hinglish" -> hinglish
            "ar" -> ar
            "bn" -> bn
            "pa", "gu", "mr" -> hi // Indian languages fallback smoothly to Hindi
            else -> en
        }
    }
